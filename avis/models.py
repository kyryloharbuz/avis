# ШАР ДАНИХ (домашні "значення-об'єкти" / value objects).
#
# Тут лежать ПРОСТІ носії даних, якими обмінюються всі частини системи.
# Це не поведінка, а факти: "знайдено об'єкт", "ось помилка", "ось команда".
# У Java це були б record-и або DTO.
#
# Чому окремим модулем: цей файл НЕ залежить ні від чого нашого (ні від cv2,
# ні від YOLO, ні від інтерфейсів). Тому і його можуть імпортувати всі інші
# шари без ризику "кільцевих імпортів" (коли A імпортує B, а B — назад A).
# Це фундамент піраміди залежностей.

from dataclasses import dataclass


# @dataclass сам згенерує конструктор, порівняння тощо (як record у Java).
@dataclass
class Detection:
    """Один виявлений об'єкт у кадрі (рамка + метадані від детектора)."""
    id: int                                  # TRACK id — який САМЕ екземпляр (лічильник трекера)
    xyxy: tuple[float, float, float, float]  # координати рамки: (x1, y1, x2, y2)
    conf: float                              # впевненість моделі (0..1)
    cls: int                                 # CLASS id — ЩО це (0=person, 56=chair, ...)
    # Людиночитана назва класу ("chair"), яку підставляє детектор із моделі.
    # Значення за замовчуванням "" робить поле НЕобов'язковим — старий код і
    # тести, що створюють Detection без name, продовжать працювати.
    name: str = ""

    # ІНКАПСУЛЯЦІЯ геометрії: формулу центру/площі тримаємо в самому об'єкті,
    # а не розмазуємо по коду. @property — доступ як до поля: det.center.
    @property
    def center(self) -> tuple[float, float]:
        """Центр рамки (cx, cy)."""
        x1, y1, x2, y2 = self.xyxy
        return (x1 + x2) / 2, (y1 + y2) / 2

    @property
    def area(self) -> float:
        """Площа рамки — непрямий показник відстані (більша = ближче)."""
        x1, y1, x2, y2 = self.xyxy
        return (x2 - x1) * (y2 - y1)


@dataclass
class ControlError:
    """Наскільки ціль не там, де треба (вхід для регулятора)."""
    error_x: float  # зсув центру цілі від центру кадру по горизонталі (пікселі)
    error_y: float  # зсув по вертикалі (пікселі)
    area: float     # поточна площа рамки (для керування дистанцією)
    # Ті самі зсуви, але НОРМОВАНІ: -1 = лівий край кадру, 0 = центр, +1 = правий.
    # Навіщо: у пікселях "багато" залежить від роздільності, а в частках — ні.
    # Саме за norm_x вирішується, чи можна вже рухатись уперед (див. controller).
    norm_x: float = 0.0
    norm_y: float = 0.0


@dataclass
class Command:
    """Команда руху для дрона (три незалежні осі, як ручки пульта)."""
    yaw: float       # + = поворот праворуч,  - = ліворуч
    vertical: float  # + = вгору,             - = вниз
    forward: float   # + = вперед (до цілі),  - = назад
