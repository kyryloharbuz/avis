# ВИЯВЛЕННЯ ПОБИТИХ КАДРІВ (втрата UDP-пакетів у відеопотоці Tello).
#
# ЧОМУ ЦЕ ПОТРІБНО. Tello жене H.264 по UDP без повторної передачі: загубився
# пакет — декодер добудовує кадр із того, що лишилось, і по картинці "розтікаються"
# зсунуті макроблоки. Заміряно на реальних польотах:
#
#     детекція на ЧИСТИХ кадрах   85%
#     детекція на ПОБИТИХ кадрах   6%     ← система практично сліпа
#
# І головне: у довгих втратах цілі 42% кадрів — побиті (при базовому рівні 10%,
# тобто вчетверо частіше). Тобто значна частина "втрат цілі" — це не втрата
# цілі взагалі, а СМІТТЯ НА ЕКРАНІ.
#
# ЧОМУ ЦЕ НЕ ЛІКУЄТЬСЯ ДЕТЕКТОРОМ. Спокуса — знизити поріг conf, щоб YOLO
# щось знаходив і на побитому кадрі. Це хибний шлях: на такому кадрі об'єкта
# фізично немає, є артефакти. Нижчий поріг дасть не ціль, а хибні спрацювання.
#
# ПРАВИЛЬНА ВІДПОВІДЬ — розрізнити два РІЗНІ стани, які система досі плутала:
#     "цілі немає"      → це ІНФОРМАЦІЯ, треба реагувати (висіти, сідати);
#     "я нічого не бачу" → це ВІДСУТНІСТЬ інформації, реагувати НЕ можна.
# Відсутність доказу — не доказ відсутності. На побитому кадрі ми просто
# зупиняємо відлік втрати: час іде, але аргументів вважати ціль зниклою немає.
#
# ЯК ВИЯВЛЯЄМО. H.264 ріже кадр на макроблоки 16x16. Коли пакет губиться,
# сусідні блоки беруться з різних місць — і на СІТЦІ 16px з'являються шви,
# яких у природному зображенні не буває. Міряємо:
#
#     перепад яскравості НА МЕЖАХ блоків / перепад ВСЕРЕДИНІ блоків
#
# У цілого кадру співвідношення ~1.1 (межі нічим не особливі). У побитого
# воно різко зростає. Метрика безрозмірна, тож не залежить від сцени,
# освітлення й роздільності — на відміну від "різкості" чи контрасту.
#
# ВАЖЛИВО ПРО ХИБНІ МЕТРИКИ. Спершу це шукали через розмитість (дисперсія
# Лапласіана) — і не знайшли: різкість на побитих кадрах не падає, а РОСТЕ
# (шви між блоками дають нові різкі краї). Тому міряти треба саме сітку.

import numpy as np


class FrameQuality:
    """Чи є кадр побитим через втрату пакетів."""

    # threshold — у скільки разів шви на сітці мають перевищити звичайний
    #   рівень цього ж потоку. 1.35 обрано із запасом: у записах медіана
    #   стабільно ~1.11, а побиті кадри дають 1.3-1.9+.
    # adapt — швидкість підлаштування базового рівня (EMA). Базовий рівень
    #   потрібен саме адаптивний: він трохи різний для 480p і 720p, а Tello
    #   вміє віддавати і те, і те залежно від того, чи прийняв налаштування.
    # row_step — рахуємо не всі рядки, а кожен 4-й: метрика усереднюється по
    #   сотнях рядків, тож точність не страждає, а ціна падає вчетверо.
    #   Це виконується НА КОЖНОМУ КАДРІ, тож дешевизна принципова.
    def __init__(self, threshold=1.35, adapt=0.02, row_step=4, warmup=30):
        self._threshold = threshold
        self._adapt = adapt
        self._row_step = row_step
        self._warmup = warmup            # скільки кадрів збираємо базу, не судячи
        self._baseline = None
        self._seen = 0

    @staticmethod
    def _grid_ratio(frame, row_step):
        """Відношення "шви на сітці 16px" / "перепади всередині блоків"."""
        # Беремо ОДИН канал замість cvtColor у сірий: артефакти видно в будь-якому,
        # а зайвого перетворення всього кадру не робимо.
        g = frame[::row_step, :, 1].astype(np.float32)
        w = g.shape[1]
        n = (w - 16) // 16
        if n < 4:
            return None
        edge_cols = 16 + 16 * np.arange(n)      # стовпці, що лежать НА межі блоку
        mid_cols = 8 + 16 * np.arange(n)        # стовпці ВСЕРЕДИНІ блоку
        edge = np.abs(g[:, edge_cols] - g[:, edge_cols - 1]).mean()
        inner = np.abs(g[:, mid_cols] - g[:, mid_cols - 1]).mean()
        if inner < 1e-6:                        # рівна пляма (напр. чорний кадр)
            return None
        return float(edge / inner)

    def is_corrupt(self, frame) -> bool:
        """True — кадру не можна вірити: на ньому сміття, а не сцена."""
        if frame is None or frame.ndim != 3:
            return False
        ratio = self._grid_ratio(frame, self._row_step)
        if ratio is None:
            return False

        if self._baseline is None:
            self._baseline = ratio
        self._seen += 1

        # Поки не набрали базу — нікого не звинувачуємо, лише вчимось.
        if self._seen <= self._warmup:
            self._baseline = (1 - self._adapt) * self._baseline + self._adapt * ratio
            return False

        corrupt = ratio > self._baseline * self._threshold

        # База оновлюється ЛИШЕ на чистих кадрах. Інакше довга серія побитих
        # кадрів підняла б базу до свого рівня, і детектор "звик" би до сміття
        # й перестав його бачити — класична пастка адаптивного порогу.
        if not corrupt:
            self._baseline = (1 - self._adapt) * self._baseline + self._adapt * ratio
        return corrupt
