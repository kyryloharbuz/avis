# БАЗОВА ВІСЬ КЕРУВАННЯ — спільна механіка для повороту, вертикалі й дистанції.
#
# Раніше зона спокою була реалізована ТРИЧІ по-різному: для повороту через
# масштабування, для вертикалі жорстким відсіком, для дистанції відніманням.
# Один і той самий задум — три реалізації, три набори помилок.
#
# Тут він один, і саме в математично правильній формі: від помилки ВІДНІМАЄМО
# ширину зони. Наслідок — на межі зони команда дорівнює НУЛЮ і далі росте
# плавно. Немає "сходинки", через яку дрон різко смикався, щойно ціль трохи
# виходила за зону.

import math

from avis.control.controller import PID


class Axis:
    """Одна вісь: помилка → мʼяка зона спокою → PID → команда."""

    def __init__(self, kp, kd, deadzone, ki=0.0):
        self._pid = PID(kp=kp, ki=ki, kd=kd)
        self._deadzone = deadzone

    @property
    def deadzone(self):
        return self._deadzone

    def shape(self, error):
        """Мʼяка зона спокою: всередині — рівно 0, за межею — плавно з нуля.
        Одиниці помилки й зони мають збігатись (px з px, метри з метрами)."""
        if abs(error) < self._deadzone:
            return 0.0
        return error - math.copysign(self._deadzone, error)

    def update(self, error, dt):
        """Порахувати команду. Всередині зони спокою PID НЕ чіпаємо взагалі,
        щоб його похідна не накопичувала шум від дрібних коливань рамки."""
        shaped = self.shape(error)
        if shaped == 0.0:
            return 0.0
        return self._pid.update(shaped, dt)

    def reset(self):
        self._pid.reset()

    def hold(self):
        """Команда 0, але зі скиданням PID — коли вісь тимчасово недостовірна.
        Окремо від reset(), щоб на місці виклику було видно НАМІР: не
        "почати спочатку", а "зараз цій осі не можна вірити"."""
        self._pid.reset()
        return 0.0
