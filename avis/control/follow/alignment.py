# ЗВʼЯЗОК ПОВОРОТУ Й РУХУ ВПЕРЕД.
#
# Дрон рухається вперед ЗА СВОЇМ НОСОМ. Якщо ціль збоку, а ми дамо повний хід
# уперед — полетимо повз неї по дузі й, найгірше, втратимо її з кадру.
# Тому рух уперед дозволяємо рівно тою мірою, якою вже дивимось на ціль.
#
# Це НЕ жорстка черга ("спершу доверни, ПОТІМ їдь") і не сліпе "одночасно" —
# це плавне поєднання: поворот працює завжди, а хід уперед наростає в міру
# вирівнювання.

class AlignmentGate:
    """Множник 0..1 для руху вперед залежно від того, наскільки ціль по центру."""

    def __init__(self, cfg):
        self._full = cfg.align_full   # до цього зсуву — повний хід
        self._stop = cfg.align_stop   # за цим — рух уперед заборонено

    def factor(self, norm_x) -> float:
        """norm_x — зсув у частках півширини кадру (0 = центр, 1 = край)."""
        offset = abs(norm_x)
        if offset <= self._full:
            return 1.0
        if offset >= self._stop:
            return 0.0
        return (self._stop - offset) / (self._stop - self._full)
