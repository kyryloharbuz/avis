# КОНФІГУРАЦІЯ стеження — усі параметри в ОДНОМУ місці, з валідацією.
#
# Навіщо окремий клас: раніше FollowController приймав 20 параметрів у
# конструкторі без жодної перевірки. Через це реально траплялись мовчазні
# поломки — наприклад, поріг чутливості 20 перебивав межу 15, і команда
# виходила БІЛЬШОЮ за дозволену. Конфіг це ловить одразу.
#
# ОДИНИЦІ ВИМІРУ вказані в кожному імені. Це навмисно: у попередній версії
# в одному класі жили пікселі, частки кадру, метри й площа в px², і плутанина
# між ними була джерелом помилок.

from dataclasses import dataclass


@dataclass
class FollowConfig:
    """Параметри стеження. Кожне поле — з одиницями виміру в назві."""

    # ── ПОВОРОТ (горизонталь) ─────────────────────────────────────────
    yaw_kp: float = 0.50              # команда на піксель помилки
    yaw_kd: float = 0.10              # демпфер
    yaw_deadzone_px: float = 24.0     # ближче за це до центру — не рухаємось

    # ── ВЕРТИКАЛЬ ─────────────────────────────────────────────────────
    # ВИМКНЕНО ЗА ЗАМОВЧУВАННЯМ. Причина — ЗВОРОТНИЙ ЗВ'ЯЗОК, який я не
    # передбачив у конструкції адаптивного рівня:
    #   дрон піднявся → ціль видно НИЖЧЕ в кадрі → відхилення → команда вниз
    #   → дрон опустився → ціль видно ВИЩЕ → команда вгору → і по колу.
    # Сам по собі це від'ємний зв'язок (самокорекція), але із затримкою Wi-Fi
    # ~250 мс і повільним навчанням рівня (tau 8 с) він переходить у КОЛИВАННЯ.
    # Саме це й спостерігалось: "піднімався та опускався" при рівній цілі.
    #
    # Чому вимкнути безпечно: Tello сам утримує висоту, а для якості стеження
    # вертикаль дає найменше — заміри показували ey≈6px навіть без неї.
    # Увімкнути назад: FollowController(vertical_enabled=True).
    vertical_enabled: bool = False
    vertical_kp: float = 0.35
    vertical_kd: float = 0.045
    vertical_deadzone_px: float = 45.0
    # Наскільки повільно вчиться "звичний рівень" цілі. Великий tau означає:
    # постійний зсув рамки ігноруємо, а швидке присідання — відпрацьовуємо.
    vertical_adapt_tau_s: float = 8.0
    # Якщо дистанція змінюється швидше — вертикаль ЗАМОРОЖУЄМО: при підльоті
    # центр рамки їде вниз сам собою (заміряно ~56px), і це не рух цілі.
    vertical_freeze_speed_mps: float = 0.35

    # ── ДИСТАНЦІЯ ─────────────────────────────────────────────────────
    # ОДНА уставка на всю систему. Раніше їх було дві (площа 94000 px² ≈ 1.44 м
    # і окремо 1.7 м), вони не збігались, і перемикання калібрування мовчки
    # змінювало поведінку — саме це й зламало рух за ціллю.
    # 0.5 м стало можливим завдяки ПОДВІЙНОМУ ВИМІРУ дистанції: доки рамка
    # ціла — міряємо висотою, а коли зріст уже не вміщається (ближче 0.88 м) —
    # переходимо на ШИРИНУ плечей, яка лишається в кадрі аж до ~0.29 м.
    # Раніше метод спирався лише на висоту, тому нижче 0.88 м система бачила
    # сталі "0.88 м" і не наближалась.
    # Зона спокою тут вужча (0.12 м): на близькій дистанції 0.15 м — це вже
    # третина уставки.
    distance_target_m: float = 0.75
    distance_kp: float = 30.0         # команда на метр помилки
    distance_kd: float = 2.0
    # Зона спокою звужена 0.25 → 0.15: широка зона означала комфортну смугу
    # 1.35-1.85 м, і дрон "правильно" не рухався майже завжди.
    # Зона спокою мусить бути ШИРШОЮ за гальмівний шлях, інакше дрон фізично
    # не встигає зупинитись і проскакує ціль. Замір: на команді 20 він пролітає
    # ще ~0.11 м після "стоп", на 55 — ~0.30 м. Тому 0.20 м, а не 0.12.
    distance_deadzone_m: float = 0.20
    # Скільки останніх вимірів усереднювати МЕДІАНОЮ. Поворот тіла дає викиди
    # (плечі вужчають → "ціль віддалилась"), і медіана їх відкидає.
    distance_median_frames: int = 5

    # ── ЗАПОБІЖНИК БЛИЗЬКОСТІ (частка кадру) ──────────────────────────
    # Не залежить ні від калібрування, ні від пози — на відміну від оцінки
    # дистанції. Заміряно: 0.75 м ≈ 39% кадру, 0.6 м ≈ 49%, 0.5 м ≈ 59%.
    frame_fill_stop: float = 0.50      # вище — рух уперед ЗАБОРОНЕНО (~0.6 м)
    frame_fill_retreat: float = 0.65   # вище — ПРИМУСОВИЙ відступ (~0.47 м)
    # Величина примусового відступу. Фіксована й завідомо вища за поріг
    # чутливості дрона (20): запобіжник, команду якого дрон не відпрацьовує,
    # гірший за відсутній — він створює хибне відчуття безпеки.
    frame_fill_retreat_command: float = 25.0
    # Відступ повільніший за наступ: позаду дрон нічого не бачить.
    retreat_factor: float = 0.5

    # ── ЗВ'ЯЗОК ПОВОРОТУ Й РУХУ ВПЕРЕД ────────────────────────────────
    # Частки ПІВШИРИНИ кадру (0 = центр, 1 = край).
    align_full: float = 0.35          # до цього — повний хід уперед
    align_stop: float = 0.80          # за цим — рух уперед заборонено

    def __post_init__(self):
        """Перевірки, яких раніше не було. Кожна ловила реальний баг."""
        if self.distance_target_m <= 0:
            raise ValueError("distance_target_m має бути додатною")
        if self.distance_deadzone_m < 0:
            raise ValueError("distance_deadzone_m не може бути відʼємною")
        if not 0 < self.frame_fill_stop < self.frame_fill_retreat <= 1.0:
            raise ValueError(
                "має бути 0 < frame_fill_stop < frame_fill_retreat <= 1")
        if self.distance_median_frames < 1:
            raise ValueError("distance_median_frames має бути >= 1")
        if self.distance_deadzone_m >= self.distance_target_m:
            raise ValueError(
                "зона спокою ширша за саму уставку — дрон ніколи не рухатиметься")
        if not 0 <= self.align_full < self.align_stop <= 1.0:
            raise ValueError(
                "має бути 0 <= align_full < align_stop <= 1 "
                f"(маємо {self.align_full} і {self.align_stop})")
        if not 0 < self.retreat_factor <= 1.0:
            raise ValueError("retreat_factor має бути в межах (0, 1]")
        for name in ("yaw_deadzone_px", "vertical_deadzone_px"):
            if getattr(self, name) < 0:
                raise ValueError(f"{name} не може бути відʼємною")
        if self.vertical_adapt_tau_s <= 0:
            raise ValueError("vertical_adapt_tau_s має бути додатною")
