# Цей файл робить теку `avis/` Python-ПАКЕТОМ.
#
# Сама наявність файлу з іменем __init__.py каже інтерпретатору:
# "усе, що лежить у цій теці, можна імпортувати як avis.щось".
# Саме тому в інших файлах працює `from avis.app import App`.
#
# У Java аналог — це структура тек, що відповідає `package avis;`.
# Тут за це відповідає один спеціальний файл.
#
# Файл ПОРОЖНІЙ навмисно: жодного коду ініціалізації пакету нам не треба.
# Його єдина робота — просто існувати. Наповнюють __init__.py лише коли
# хочуть, наприклад, скоротити імпорти (from avis import Detector).
#
# Про подвійні підкреслення __...__ ("dunder", від "double underscore"):
# такі імена зарезервовані самим Python для спеціальних речей. __init__.py —
# спеціальний файл пакету; __init__ (побачиш нижче в класах) — спеціальний
# метод-конструктор. Це та сама ідея "магічного" імені, але в різних місцях.
